/// Yükseltilebilir ailenin belirli seviyedeki anahtarı (ör. 'trap', 2 → 'trap2').
String? familyKeyAtLevel(String family, int level) {
  final k = '$family$level';
  return kCards.containsKey(k) ? k : null;
}

/// A held upgraded card can still be played at any lower level that its
/// current mana affords. The hand stores the highest unlocked family member,
/// while the turn UI lets the player choose the actual level.
int minimumManaFor(CardDef card) {
  if (!card.upgradeable) return card.mana;
  final baseKey = familyKeyAtLevel(card.family, 1);
  return baseKey == null ? card.mana : kCards[baseKey]!.mana;
}

