import 'board.dart';
import 'move.dart';
import 'move_gen.dart';
import 'piece.dart';

/// The complete result state of a cards-free orthodox chess game.
///
/// A position can be claimable without the game being over. That distinction
/// is intentional: the fifty-move and threefold-repetition rules are claims,
/// while the seventy-five-move and fivefold-repetition rules are automatic.
enum ChessGameStatus {
  ongoing,
  checkmate,
  stalemate,
  drawByDeadPosition,
  drawBySeventyFiveMove,
  drawByFivefoldRepetition,
  drawByFiftyMoveClaim,
  drawByThreefoldRepetitionClaim,
  drawByAgreement,
}

/// Cards-free orthodox chess game state.
///
/// [Board] and [MoveGen] provide immutable positions and legal move
/// generation. This class adds the history-dependent FIDE rules and a single
/// validated move entry point so a UI cannot accidentally apply a pseudo-legal
/// move or turn a claimable draw into an automatic one.
class ChessGame {
  ChessGame({Board? initialBoard}) : _board = initialBoard ?? Board.start() {
    _recordPosition();
    _refreshStatus();
  }

  Board _board;
  final List<Move> _history = [];
  final Map<String, int> _positionCounts = {};
  ChessGameStatus _status = ChessGameStatus.ongoing;

  Board get board => _board;

  /// Canonical moves as generated by the legal move generator.
  List<Move> get legalMoves =>
      isOver ? const <Move>[] : List<Move>.unmodifiable(MoveGen.legal(_board));

  List<Move> get history => List<Move>.unmodifiable(_history);

  ChessGameStatus get status => _status;

  bool get isOver => _status != ChessGameStatus.ongoing;

  bool get inCheck => MoveGen.inCheck(_board, _board.turn);

  PieceColor? get winner =>
      _status == ChessGameStatus.checkmate ? _board.turn.opposite : null;

  bool get isDraw =>
      _status == ChessGameStatus.stalemate ||
      _status == ChessGameStatus.drawByDeadPosition ||
      _status == ChessGameStatus.drawBySeventyFiveMove ||
      _status == ChessGameStatus.drawByFivefoldRepetition ||
      _status == ChessGameStatus.drawByFiftyMoveClaim ||
      _status == ChessGameStatus.drawByThreefoldRepetitionClaim ||
      _status == ChessGameStatus.drawByAgreement;

  String get currentPositionKey => MoveGen.repetitionKey(_board);

  int get currentPositionCount => _positionCounts[currentPositionKey] ?? 0;

  /// A fifty-move draw is claimable, but is not automatic under FIDE rules.
  bool get canClaimFiftyMove => !isOver && _board.isFiftyMoveRule;

  /// A threefold draw is claimable once the current position has appeared
  /// three times with the same side to move and the same legal rights.
  bool get canClaimThreefoldRepetition => !isOver && currentPositionCount >= 3;

  /// Whether [move] would make the current position occur for the third time.
  /// The move is checked against the actual legal move list first.
  bool canClaimThreefoldByMove(Move move) {
    if (isOver) return false;
    final canonical = _canonicalMove(move);
    if (canonical == null) return false;
    final next = _board.apply(canonical);
    final key = MoveGen.repetitionKey(next);
    return (_positionCounts[key] ?? 0) + 1 >= 3;
  }

  /// Apply one legal move. Flags on [move] are optional; from/to/promotion are
  /// resolved against the canonical move returned by [MoveGen].
  bool play(Move move) {
    if (isOver) return false;
    final canonical = _canonicalMove(move);
    if (canonical == null) return false;
    _board = _board.apply(canonical);
    _history.add(canonical);
    _recordPosition();
    _refreshStatus();
    return true;
  }

  /// Claim a fifty-move draw without altering the position.
  bool claimFiftyMove() {
    if (!canClaimFiftyMove) return false;
    _status = ChessGameStatus.drawByFiftyMoveClaim;
    return true;
  }

  /// Claim a threefold draw either for the current position or for an
  /// announced legal move, as permitted by the FIDE claim procedure.
  bool claimThreefoldRepetition({Move? intendedMove}) {
    final canClaim =
        intendedMove == null
            ? canClaimThreefoldRepetition
            : canClaimThreefoldByMove(intendedMove);
    if (!canClaim) return false;
    _status = ChessGameStatus.drawByThreefoldRepetitionClaim;
    return true;
  }

  /// Finish a game by mutual agreement. The caller is responsible for
  /// obtaining the other player's acceptance before invoking this method.
  bool agreeDraw() {
    if (isOver) return false;
    _status = ChessGameStatus.drawByAgreement;
    return true;
  }

  void _recordPosition() {
    final key = MoveGen.repetitionKey(_board);
    _positionCounts[key] = (_positionCounts[key] ?? 0) + 1;
  }

  Move? _canonicalMove(Move requested) {
    for (final legal in MoveGen.legal(_board)) {
      if (legal.from == requested.from &&
          legal.to == requested.to &&
          legal.promotion == requested.promotion) {
        return legal;
      }
    }
    return null;
  }

  void _refreshStatus() {
    final moves = MoveGen.legal(_board);
    if (moves.isEmpty) {
      _status =
          MoveGen.inCheck(_board, _board.turn)
              ? ChessGameStatus.checkmate
              : ChessGameStatus.stalemate;
      return;
    }

    // Checkmate/stalemate above take precedence over automatic counters.
    if (_board.isInsufficientMaterial) {
      _status = ChessGameStatus.drawByDeadPosition;
      return;
    }
    if (_board.isSeventyFiveMoveRule) {
      _status = ChessGameStatus.drawBySeventyFiveMove;
      return;
    }
    if (currentPositionCount >= 5) {
      _status = ChessGameStatus.drawByFivefoldRepetition;
      return;
    }
    _status = ChessGameStatus.ongoing;
  }
}
